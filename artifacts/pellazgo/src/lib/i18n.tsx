type TranslationKeys = keyof typeof translations.sq;

interface I18nContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TranslationKeys) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'sq',
  setLang: () => {},
  t: (k) => k,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    return (localStorage.getItem('pellazgo_lang') as Lang) || 'sq';
  });

  const setLang = (l: Lang) => {
    localStorage.setItem('pellazgo_lang', l);
    setLangState(l);
  };

  const t = (key: TranslationKeys): string => {
    return (translations[lang] as any)[key] || (translations.en as any)[key] || key;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
